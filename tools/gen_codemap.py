"""Generate a deterministic Python symbol index for the explicit code directories."""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORIES = ("src", "tests", "tools")


class SymbolIndex(ast.NodeVisitor):
    def __init__(self):
        self.scope = []
        self.symbols = []

    def _definition(self, node, kind):
        name = ".".join([*self.scope, node.name])
        self.symbols.append((name, kind, node.lineno))
        self.scope.append(node.name)
        self.generic_visit(node)
        self.scope.pop()

    def visit_ClassDef(self, node):
        self._definition(node, "class")

    def visit_FunctionDef(self, node):
        self._definition(node, "function")

    def visit_AsyncFunctionDef(self, node):
        self._definition(node, "async function")

    def visit_Assign(self, node):
        if not self.scope:
            for target in node.targets:
                if isinstance(target, ast.Name):
                    self.symbols.append((target.id, "value", node.lineno))
        self.generic_visit(node)


def main():
    lines = [
        "# Code map",
        "",
        "Generated by `python3 tools/gen_codemap.py`; do not edit manually.",
        "",
        "Read [ARCHITECTURE.md](ARCHITECTURE.md) for boundaries and invariants.",
        "",
    ]
    for directory in DIRECTORIES:
        for path in sorted((ROOT / directory).rglob("*.py")):
            relative = path.relative_to(ROOT).as_posix()
            index = SymbolIndex()
            index.visit(ast.parse(path.read_text(encoding="utf-8")))
            lines.extend([f"## `{relative}`", ""])
            if not index.symbols:
                lines.extend(["Package or module entry point; no defined symbols.", ""])
                continue
            lines.extend(["| Symbol | Kind | Address |", "| --- | --- | --- |"])
            for name, kind, line in index.symbols:
                lines.append(f"| `{name}` | {kind} | [{relative}:{line}](../{relative}#L{line}) |")
            lines.append("")
    destination = ROOT / "docs" / "CODEMAP.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    print("Generated docs/CODEMAP.md")


if __name__ == "__main__":
    main()
